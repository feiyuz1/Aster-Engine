bool waitForDatagram(UdpSocket& socket, UdpEndpoint& sender, std::vector<std::uint8_t>& payload)
{
    for (int attempt = 0; attempt < 200; ++attempt)
    {
        if (socket.receive(sender, payload))
            return true;
        std::this_thread::sleep_for(std::chrono::milliseconds(1));
    }
    return false;
}

bool matrixDifferent(const Mat4& left, const Mat4& right)
{
    for (int row = 0; row < 4; ++row)
        for (int column = 0; column < 4; ++column)
            if (std::abs(left.at(row, column) - right.at(row, column)) > 0.00001f)
                return true;
    return false;
}
